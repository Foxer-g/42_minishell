#include "minishell.h"

int	echo(char **argv, t_ffile out)
{
	bool	nl;

	argv++;
	
	nl = !!ft_strcmp(*argv, "-n");
	if (!nl)
		argv++;
	while (*argv)
	{
		ft_putstr_fd(*argv, out);
		argv++;
		if (*argv)
			ft_putchar_fd(' ', out);
	}
	if (nl)
		ft_putchar_fd('\n', out);
	return (0);
}
