#include "minishell.h"

int	echo(t_command cmd, char ***env)
{
	bool	nl;

	(void)env;
	nl = true;
	cmd.args++;
	if (*cmd.args)
		nl = !!ft_strcmp(*cmd.args, "-n");
	if (!nl)
		cmd.args++;
	while (*cmd.args)
	{
		ft_putstr_fd(*cmd.args, cmd.outfd);
		cmd.args++;
		if (*cmd.args)
			ft_putchar_fd(' ', cmd.outfd);
	}
	if (nl)
		ft_putchar_fd('\n', cmd.outfd);
	return (0);
}
