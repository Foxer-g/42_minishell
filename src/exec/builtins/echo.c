#include "minishell.h"

int	echo(int ac, char **av, t_ffile out)
{
	bool	nl;

	av++;
	
	nl = !!ft_strcmp(*av, "-n");
	if (!nl)
		av++;
	while (*av)
	{
		ft_putstr_fd(*av, out);
		av++;
		if (*av)
			ft_putchar_fd(' ', out);
	}
	if (nl)
		ft_putchar_fd('\n', out);
	return (0);
}
