#include "minishell.h"

int	env(int ac, char **ev)
{
	uintmax_t	i;

	if (ac != 1)
	{
		printf("env: expected 0 arguments (args unsupported in minishell);"
			" got %d\n", ac - 1);
		return (1);
	}
	i = 0;
	while (ev[i])
	{
		if (ft_strchr(ev[i], '='))
			printf("%s\n", ev[i]);
		i++;
	}
	return (0);
}
