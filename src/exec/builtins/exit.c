#include "minishell.h"

int	minishell_exit(t_command cmd, char ***ev)
{
	const uintmax_t	ac = ft_nt_tablen((void *)cmd.args);

	(void)ev;
	if (ac == 1)
		return (-1);
	else if (ac == 2)
		exit(-(ft_atoi(cmd.args[1]) % 257));
	printf("exit: too many arguments");
	return (1);
}
