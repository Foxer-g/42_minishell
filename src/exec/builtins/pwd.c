#include "minishell.h"

int	pwd(t_command cmd, char ***env)
{
	if (cmd.infd < 0 || cmd.outfd < 0)
		return (1);
	ft_dprintf(cmd.outfd, "%s\n", ft_get_env("PWD", *env));
	return (0);
}
