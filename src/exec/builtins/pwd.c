#include "minishell.h"

int	pwd(t_command cmd, char ***env)
{
	const uintmax_t	ac = ft_nt_tablen((void*)cmd.args);

	if (ac != 1)
	{
		printf("pwd: expected 0 arguments; got %lu\n", ac - 1);
		return (1);
	}
	printf("%s\n", ft_get_env("PWD", *env));
	return (0);
}
