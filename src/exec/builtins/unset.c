#include "minishell.h"

int	unset(char **vars, char ***env)
{
	char	**target;

	while (*vars)
	{
		if (ft_strchr(*vars, '='))
		{
			set_env(*vars, env, "");
			return (0);
		}
		while (*env++)
		{
			if (ft_strcmp(**(env - 1), *vars))
				continue ;
			target = *env;
			break ;
		}
		if (*env)
			free(*target);
		while (*env && *(env + 1))
			env++;
		*target = **env;
		**env = NULL;
		vars++;
	}
	return (0);
}
